IF DB_ID(N'BDD') IS NULL
BEGIN
    CREATE DATABASE BDD;
END;
GO

USE BDD;
GO

IF OBJECT_ID(N'dbo.TBL_USER', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TBL_USER (
        id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TBL_USER PRIMARY KEY,
        username VARCHAR(255) NOT NULL CONSTRAINT UQ_TBL_USER_USERNAME UNIQUE,
        [password] VARCHAR(255) NOT NULL,
        [role] VARCHAR(20) NOT NULL CONSTRAINT CK_TBL_USER_ROLE CHECK ([role] IN ('admin', 'normal'))
    );
END;
GO

IF OBJECT_ID(N'dbo.TBL_SONG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TBL_SONG (
        id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TBL_SONG PRIMARY KEY,
        song_name VARCHAR(255) NOT NULL,
        file_path VARCHAR(500) NOT NULL,
        reproductions INT NOT NULL CONSTRAINT DF_TBL_SONG_REPRODUCTIONS DEFAULT (0)
    );
END;
GO
